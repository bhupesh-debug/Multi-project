"""Automated management-reporting workflow.

Generates, for a chosen reporting month:
* reports/variance_report_<YYYY-MM>.md  — narrative variance report
* reports/management_report_<YYYY-MM>.xlsx — workbook: Summary, Variance
  by strategy, Profit bridge, Cost lines, Forecast outlook, Anomaly flags,
  KPI dashboard
* reports/model_report.md — forecast model comparison + anomaly results

This is the "automated reporting workflow" from the JD: one command
(`python run.py --month 2025-12`) reproduces the whole monthly pack.
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill
from openpyxl.utils.dataframe import dataframe_to_rows

HEADER_FILL = PatternFill("solid", fgColor="1F4E79")
HEADER_FONT = Font(color="FFFFFF", bold=True)
TITLE_FONT = Font(bold=True, size=14)


def _md(df: pd.DataFrame) -> str:
    """Markdown table with readable numbers: months as YYYY-MM, floats
    rounded to 3 decimals (no scientific notation)."""
    d = df.copy()
    if "month" in d.columns and pd.api.types.is_datetime64_any_dtype(d["month"]):
        d["month"] = d["month"].dt.strftime("%Y-%m")
    for c in d.columns:
        if pd.api.types.is_float_dtype(d[c]):
            # Money columns print as integers (no scientific notation);
            # ratios/percentages keep 3 decimals.
            if d[c].notna().all() and (d[c].abs() > 1000).all():
                d[c] = d[c].round(0).astype("int64")
            else:
                d[c] = d[c].round(3)
    return d.to_markdown(index=False)


def _write_sheet(wb: Workbook, title: str, df: pd.DataFrame) -> None:
    ws = wb.create_sheet(title)
    for r_idx, row in enumerate(dataframe_to_rows(df, index=False, header=True), start=1):
        for c_idx, value in enumerate(row, start=1):
            cell = ws.cell(row=r_idx, column=c_idx, value=value)
            if r_idx == 1:
                cell.fill = HEADER_FILL
                cell.font = HEADER_FONT
    for col in ws.columns:
        ws.column_dimensions[col[0].column_letter].width = 22


def build_workbook(path: Path, month_label: str, summary: pd.DataFrame,
                   strat_var: pd.DataFrame, bridge: pd.DataFrame,
                   cost_lines: pd.DataFrame, outlook: pd.DataFrame,
                   anomalies: pd.DataFrame, kpis: pd.DataFrame) -> Path:
    wb = Workbook()
    wb.remove(wb.active)
    ws = wb.create_sheet("Summary")
    ws["A1"] = f"Management Report — {month_label} (SYNTHETIC DATA)"
    ws["A1"].font = TITLE_FONT
    for r_idx, row in enumerate(dataframe_to_rows(summary, index=False, header=True), start=3):
        for c_idx, value in enumerate(row, start=1):
            cell = ws.cell(row=r_idx, column=c_idx, value=value)
            if r_idx == 3:
                cell.fill = HEADER_FILL
                cell.font = HEADER_FONT
    for col in ws.columns:
        ws.column_dimensions[col[0].column_letter].width = 26
    _write_sheet(wb, "Variance by strategy", strat_var)
    _write_sheet(wb, "Profit bridge", bridge)
    _write_sheet(wb, "Cost lines", cost_lines)
    _write_sheet(wb, "Forecast outlook", outlook)
    _write_sheet(wb, "Anomaly flags", anomalies)
    _write_sheet(wb, "KPI dashboard", kpis)
    wb.save(path)
    return path


def build_markdown_report(path: Path, month_label: str, firm_row: pd.Series,
                          bridge: pd.DataFrame, cost_lines: pd.DataFrame,
                          strat_var_latest: pd.DataFrame, outlook: pd.DataFrame,
                          anomalies: pd.DataFrame, best_model: str,
                          mape: dict) -> Path:
    rev_var = firm_row["revenue_actual"] - firm_row["revenue_budget"]
    cost_var = firm_row["cost_actual"] - firm_row["cost_budget"]
    profit_var = firm_row["operating_profit_actual"] - firm_row["operating_profit_budget"]
    margin = firm_row["operating_profit_actual"] / firm_row["revenue_actual"] * 100
    flags = anomalies.loc[anomalies["verdict"] == "ANOMALY", "month"].dt.strftime("%b %Y").tolist()
    lines = [
        f"# Monthly Variance Report — {month_label}",
        "",
        "> **ALL DATA IS SYNTHETIC.** Generated by code (seed 42) for demonstration. "
        "No real Asymptote Capital figures, fund performance, or market data are used.",
        "",
        "## Executive summary",
        "",
        f"- Revenue **${firm_row['revenue_actual']:,.0f}** vs budget "
        f"${firm_row['revenue_budget']:,.0f} — variance **${rev_var:+,.0f}** "
        f"({rev_var / firm_row['revenue_budget']:+.1%}).",
        f"- Total cost **${firm_row['cost_actual']:,.0f}** vs budget "
        f"${firm_row['cost_budget']:,.0f} — variance **${cost_var:+,.0f}** "
        f"({'overrun' if cost_var > 0 else 'saving'}).",
        f"- Operating profit **${firm_row['operating_profit_actual']:,.0f}** vs budget "
        f"${firm_row['operating_profit_budget']:,.0f} — variance **${profit_var:+,.0f}**; "
        f"operating margin **{margin:.1f}%**.",
        f"- AUM **${firm_row['aum_actual_m']:,.0f}m** vs budget ${firm_row['aum_budget_m']:,.0f}m.",
        f"- Anomaly months in the 24-month history: {', '.join(flags) if flags else 'none'}.",
        "",
        "## Profit bridge (budget → actual)",
        "",
        _md(bridge),
        "",
        "## Cost variance by line",
        "",
        _md(cost_lines),
        "",
        "## Revenue variance by strategy",
        "",
        _md(strat_var_latest),
        "",
        "## Forecast outlook (next 3 months)",
        "",
        f"Best model on the 6-month hold-out: **{best_model}** "
        f"(MAPE {mape[best_model]:.1%}; all models: " +
        "; ".join(f"{k} {v:.1%}" for k, v in mape.items()) + ").",
        "",
        _md(outlook),
        "",
        "## Anomaly flags (rule + Isolation Forest)",
        "",
        _md(anomalies.loc[anomalies["verdict"] != "Normal"])
        if (anomalies["verdict"] != "Normal").any() else "No anomalies or watch items.",
        "",
        "## Limitations",
        "",
        "- Synthetic data only — variances, shocks and forecasts demonstrate the "
        "pipeline, not real firm performance.",
        "- Forecast intervals assume stable residual volatility; a regime change "
        "or large redemption would break them.",
        "- Anomaly detection is unsupervised on 24 monthly points — small sample, "
        "so WATCH items need human review, not automatic action.",
        "",
        "_Prepared by Bhupesh Chandra Dimri — automated reporting workflow, "
        "`python run.py --month YYYY-MM`._",
    ]
    path.write_text("\n".join(lines))
    return path
