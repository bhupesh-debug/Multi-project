"""KPI dashboard workbook (Excel) — the JD's dashboard deliverable.

Builds ``reports/kpi_dashboard.xlsx`` with:
* Cover — what this is, synthetic-data warning, how to read it.
* KPI_Summary — synthetic business KPIs (AUM, revenue, costs, margin,
  headcount) with latest values and 12-month changes.
* Backtest — strategy metrics table + equity-curve line chart.
* Scenarios — bull/base/bear table + Monte Carlo summary.
* Models — model comparison table + bar chart.
* Data_KPIs / Data_Equity — the underlying tables behind the charts.

All values come from the pipeline run; nothing is hand-typed.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.chart import BarChart, LineChart, Reference
from openpyxl.styles import Font
from openpyxl.utils import get_column_letter

TITLE_FONT = Font(bold=True, size=14, color="1F4E79")
HEADER_FONT = Font(bold=True, color="FFFFFF")
HEADER_FILL = "1F4E79"


def _write_table(ws, df: pd.DataFrame, start_row: int = 1, title: str | None = None):
    from openpyxl.styles import PatternFill

    row = start_row
    if title:
        ws.cell(row=row, column=1, value=title).font = TITLE_FONT
        row += 2
    header_row = row
    for j, col in enumerate(df.columns, start=1):
        cell = ws.cell(row=header_row, column=j, value=str(col))
        cell.font = HEADER_FONT
        cell.fill = PatternFill("solid", fgColor=HEADER_FILL)
    for i, (_, record) in enumerate(df.iterrows(), start=header_row + 1):
        for j, value in enumerate(record, start=1):
            ws.cell(row=i, column=j, value=value)
    for j in range(1, len(df.columns) + 1):
        ws.column_dimensions[get_column_letter(j)].width = 22
    return header_row, header_row + len(df)


def build_dashboard(
    out_path: Path,
    kpis: pd.DataFrame,
    backtest_metrics: pd.DataFrame,
    equity_curves: dict[str, pd.DataFrame],
    scenarios: pd.DataFrame,
    mc_summary: dict,
    model_results: pd.DataFrame,
) -> Path:
    wb = Workbook()

    # ---- Cover ----
    cover = wb.active
    cover.title = "Cover"
    cover["A1"] = "Asymptote Systematic Signal — KPI Dashboard"
    cover["A1"].font = Font(bold=True, size=16, color="1F4E79")
    cover["A3"] = "SYNTHETIC DATA — demonstration only. Not real market data, not"
    cover["A4"] = "Asymptote Capital data, and not evidence of a trading edge."
    cover["A6"] = "Contents: KPI_Summary (firm KPIs) | Backtest (strategy KPIs) |"
    cover["A7"] = "Scenarios (bull/base/bear + Monte Carlo) | Models (model comparison)"
    cover["A9"] = "Author: Bhupesh Chandra Dimri. Generated by run.py (seed 42)."
    cover.column_dimensions["A"].width = 90

    # ---- KPI summary ----
    ws = wb.create_sheet("KPI_Summary")
    latest = kpis.iloc[-1]
    year_ago = kpis.iloc[-13] if len(kpis) > 12 else kpis.iloc[0]
    summary = pd.DataFrame(
        [
            {
                "KPI": "AUM ($m)",
                "Latest": round(float(latest["aum_usd_m"]), 1),
                "12m ago": round(float(year_ago["aum_usd_m"]), 1),
                "Change %": round(
                    100 * (latest["aum_usd_m"] / year_ago["aum_usd_m"] - 1), 1
                ),
            },
            {
                "KPI": "Revenue ($m, annualised)",
                "Latest": round(float(latest["revenue_usd_m"]), 2),
                "12m ago": round(float(year_ago["revenue_usd_m"]), 2),
                "Change %": round(
                    100 * (latest["revenue_usd_m"] / year_ago["revenue_usd_m"] - 1), 1
                ),
            },
            {
                "KPI": "Operating margin (%)",
                "Latest": round(float(latest["operating_margin_pct"]), 1),
                "12m ago": round(float(year_ago["operating_margin_pct"]), 1),
                "Change %": round(
                    float(latest["operating_margin_pct"] - year_ago["operating_margin_pct"]), 1
                ),
            },
            {
                "KPI": "Headcount",
                "Latest": int(latest["headcount"]),
                "12m ago": int(year_ago["headcount"]),
                "Change %": round(
                    100 * (latest["headcount"] / year_ago["headcount"] - 1), 1
                ),
            },
            {
                "KPI": "Revenue per head ($k)",
                "Latest": round(float(latest["revenue_per_head_usd_k"]), 0),
                "12m ago": round(float(year_ago["revenue_per_head_usd_k"]), 0),
                "Change %": round(
                    100
                    * (latest["revenue_per_head_usd_k"] / year_ago["revenue_per_head_usd_k"] - 1),
                    1,
                ),
            },
        ]
    )
    _write_table(ws, summary, title="Business KPIs — synthetic firm (latest month)")

    # ---- Backtest ----
    ws = wb.create_sheet("Backtest")
    hr, _ = _write_table(
        ws, backtest_metrics, title="Strategy backtest — test period (synthetic)"
    )
    # Equity data + line chart
    eq = pd.DataFrame({"date": equity_curves["ml_signal"]["date"]})
    for name, daily in equity_curves.items():
        eq[name] = daily["equity"].to_numpy()
    data_ws = wb.create_sheet("Data_Equity")
    for j, col in enumerate(eq.columns, start=1):
        data_ws.cell(row=1, column=j, value=str(col))
    for i, (_, record) in enumerate(eq.iterrows(), start=2):
        for j, value in enumerate(record, start=1):
            data_ws.cell(row=i, column=j, value=value)
    chart = LineChart()
    chart.title = "Equity curves (growth of $1, synthetic)"
    chart.y_axis.title = "Equity"
    chart.x_axis.title = "Date"
    data = Reference(data_ws, min_col=2, min_row=1, max_row=len(eq) + 1, max_col=1 + len(equity_curves))
    chart.add_data(data, titles_from_data=True)
    chart.height, chart.width = 7.5, 15
    ws.add_chart(chart, f"A{hr + 3}")

    # ---- Scenarios ----
    ws = wb.create_sheet("Scenarios")
    _write_table(ws, scenarios, title="Deterministic scenarios — 1-year outlook")
    mc_df = pd.DataFrame([mc_summary])
    _write_table(ws, mc_df, start_row=len(scenarios) + 6, title="Monte Carlo — 2,000 paths")

    # ---- Models ----
    ws = wb.create_sheet("Models")
    hr, _ = _write_table(ws, model_results, title="Model comparison — test set")
    chart = BarChart()
    chart.type = "col"
    chart.title = "Model comparison (accuracy / ROC-AUC / F1)"
    chart.y_axis.title = "Score"
    data = Reference(ws, min_col=2, min_row=hr, max_row=hr + len(model_results), max_col=4)
    cats = Reference(ws, min_col=1, min_row=hr + 1, max_row=hr + len(model_results))
    chart.add_data(data, titles_from_data=True)
    chart.set_categories(cats)
    chart.height, chart.width = 7.5, 15
    ws.add_chart(chart, f"A{hr + len(model_results) + 3}")

    wb.save(out_path)
    return out_path
