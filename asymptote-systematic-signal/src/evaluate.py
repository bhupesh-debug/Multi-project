"""Evaluation reporting: metrics tables + the written model report.

``evaluate.py`` is the reporting layer — it takes the outputs of
``model.py`` / ``backtest.py`` / ``scenario.py`` and writes the human-
readable ``reports/model_report.md`` (numbers filled in from the actual
run, never hand-typed).
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd


def write_model_report(
    out_path: Path,
    model_results: pd.DataFrame,
    rule_result: dict,
    backtest_metrics: pd.DataFrame,
    scenarios: pd.DataFrame,
    mc_summary: dict,
    importances: pd.DataFrame,
    regime_accuracy: float,
    n_train: int,
    n_test: int,
) -> Path:
    """Render the model report from the real run outputs."""
    best = model_results.sort_values("f1", ascending=False).iloc[0]
    best_bt = backtest_metrics.iloc[0]
    lines = [
        "# Model Report — Asymptote Systematic Signal (SYNTHETIC DATA)",
        "",
        "> **All data in this project is synthetic.** Prices, regimes, KPIs and",
        "> backtest results are generated by code with seed 42. Nothing here is",
        "> real market data, real Asymptote data, or evidence of a live edge.",
        "",
        "## 1. What was built",
        "",
        "A regime-aware systematic signal engine: given trailing price features",
        "for four synthetic asset proxies, predict whether each asset will be",
        "higher in 20 trading days, convert the prediction into a daily",
        "long/flat/short position, and backtest it against a momentum rule and",
        "buy-and-hold. A KPI dashboard and a bull/base/bear scenario engine sit",
        "on top, matching the JD's dashboard, KPI and scenario-analysis work.",
        "",
        f"Training rows: **{n_train:,}** (2019–2023). Test rows: **{n_test:,}** "
        "(2024–2025, chronological split — no shuffling).",
        "",
        "## 2. Model comparison (test set, binary up/down in 20 days)",
        "",
        model_results.to_markdown(index=False),
        "",
        f"Rule baseline: accuracy **{rule_result['accuracy']}**, "
        f"F1 **{rule_result['f1']}** (no AUC — a rule has no probabilities).",
        "",
        f"Best model by F1: **{best['model']}** "
        f"(accuracy {best['accuracy']}, ROC-AUC {best['roc_auc']}, "
        f"F1 {best['f1']}).",
        "",
        f"Secondary 3-class regime classifier (bull/range/bear) accuracy: "
        f"**{regime_accuracy:.4f}**.",
        "",
        "## 3. Top 5 features (random forest)",
        "",
        importances.head(5).to_markdown(index=False),
        "",
        "## 4. Backtest (test period, 5 bps cost per position change)",
        "",
        backtest_metrics.to_markdown(index=False),
        "",
        f"Best backtest by Sharpe: **{best_bt['strategy']}** "
        f"(Sharpe {best_bt['sharpe']}, CAGR {best_bt['cagr_pct']}%, "
        f"max drawdown {best_bt['max_drawdown_pct']}%).",
        "",
        "## 5. Scenario analysis (1-year outlook, ML-signal strategy)",
        "",
        scenarios.to_markdown(index=False),
        "",
        "Monte Carlo (2,000 block-bootstrapped 1-year paths):",
        "",
        f"- Terminal wealth of $1: p5 **{mc_summary['terminal_p5']}**, "
        f"median **{mc_summary['terminal_p50']}**, "
        f"p95 **{mc_summary['terminal_p95']}**",
        f"- Probability of ending below $1: **{mc_summary['prob_loss_pct']}%**",
        f"- Probability of a >10% drawdown: "
        f"**{mc_summary['prob_dd_gt_10pct']}%**",
        f"- 5% expected shortfall (terminal wealth): "
        f"**{mc_summary['expected_shortfall_5pct']}**",
        "",
        "## 6. How to read these results honestly",
        "",
        "- The signal beats the rule baseline on this synthetic sample — that "
        "is expected, because the synthetic generator itself embeds",
        "  momentum and regime persistence the model can learn.",
        "- **This is a pipeline demonstration, not a trading strategy.** Real",
        "  data has transaction costs, capacity limits, borrow costs, regime",
        "  breaks and data errors that synthetic data does not.",
        "- Before any real use: replace synthetic prices with real,",
        "  survivorship-bias-free data; use purged walk-forward validation;",
        "  add slippage and borrow-cost modelling; and get an independent",
        "  review of the backtest.",
        "",
        "## 7. Reproduce",
        "",
        "```bash",
        "python -m venv .venv && .venv/bin/pip install -r requirements.txt",
        ".venv/bin/python run.py",
        "```",
        "",
        "Charts: `reports/charts/`. KPI dashboard: "
        "`reports/kpi_dashboard.xlsx`.",
        "",
    ]
    out_path.write_text("\n".join(lines), encoding="utf-8")
    return out_path
